# 5. key= 는 sorted / sort 안에만 쓴다. x에는 원소 하나가 들어온다
#    (헷갈린 곳: print 안에 key를 넣은 것, x[0]/x[1] 고르기)
# ──────────────────────────────────────────────
# [따라 쓰기]
words = ["banana", "kiwi", "apple"]

print(sorted(words, key=len))
# [예상] ['kiwi', 'apple', 'banana']   ← 각 단어를 len(단어)로 바꿔서 비교

print(sorted(words, key=lambda x: x[1]))
# [예상] ['banana', 'kiwi', 'apple']   ← x는 단어 하나, x[1]은 두 번째 글자 a, i, p

pairs = [("kim", 90), ("lee", 80), ("park", 95)]
print(sorted(pairs, key=lambda x: x[1]))
# [예상] [('lee', 80), ('kim', 90), ('park', 95)]   ← x는 묶음 하나, x[1]은 점수

# 정렬(key)과 꺼내기(p[0])는 다른 일이다
for p in sorted(pairs, key=lambda x: x[1], reverse=True):
    print(p[0])
# [예상] park / kim / lee

# [바꿔 쓰기] 마지막 for문에서 이름순(x[0])으로 정렬하면 출력 순서는?


